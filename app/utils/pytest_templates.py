from __future__ import annotations

from textwrap import dedent

from app.models.schemas import APIType


def build_pytest_ini() -> str:
    """Return a pytest.ini that makes a ticket's output folder runnable standalone."""
    return dedent(
        """\
        [pytest]
        markers =
            positive: Happy-path test scenarios
            negative: Error and failure test scenarios
            edge: Boundary and edge-case test scenarios
        asyncio_mode = auto
        """
    )


