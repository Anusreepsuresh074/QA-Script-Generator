_REST_JEST_STANDARDS = """Internal QA automation standards for Jest + REST APIs (MUST follow exactly):
- Generate a single valid JavaScript test file (.test.js).
- Import setup helpers: const { BASE_URL, createClient } = require('./setup');
- Create the axios client once at the top of the describe block: const client = createClient();
- Group tests with describe('<ticket_id>: <summary>', () => { ... }).
- One test() per scenario; name: test('<type>: <scenario name>', async () => { ... }).
- Structure: // Arrange / // Act / // Assert comments in each test.
- Assertions: expect(response.status).toBe(200); expect(response.data).toBeDefined(); etc.
- For negative tests: expect([400, 401, 403, 404, 422]).toContain(response.status);
- Build full paths: const url = `/your/endpoint`; (axios uses baseURL from client)
- Do NOT import or redefine setup helpers.
- Do NOT use beforeAll/afterAll for client creation (use top-level in describe).
- Output ONLY valid JavaScript source for a single .test.js file. No markdown fences, no explanation."""

_GRAPHQL_JEST_STANDARDS = """Internal QA automation standards for Jest + GraphQL (MUST follow exactly):
- Generate a single valid JavaScript .test.js file.
- Import: const { GRAPHQL_URL, createGqlClient, gql } = require('./setup');
- Create client once: const client = createGqlClient();
- Group with describe('<ticket_id>: <summary>', () => { ... }).
- One test() per scenario.
- Structure: // Arrange / // Act / // Assert comments.
- Call: const response = await gql(client, query, variables);
- GraphQL always returns HTTP 200; check response.data.data for success, response.data.errors for errors.
- Positive: expect(response.status).toBe(200); expect(response.data.errors).toBeUndefined();
- Negative: expect(response.data.errors).toBeDefined(); expect(response.data.errors.length).toBeGreaterThan(0);
- Write queries as template literals: const query = `query { ... }`;
- Output ONLY valid JavaScript. No markdown fences, no explanation."""

_WEBSOCKET_JEST_STANDARDS = """Internal QA automation standards for Jest + WebSocket (MUST follow exactly):
- Generate a single valid JavaScript .test.js file.
- Import: const { WS_URL, connect, sendAndReceive } = require('./setup');
- Add at top: jest.setTimeout(15000); for WS tests.
- Group with describe('<ticket_id>: <summary>', () => { ... }).
- Each test closes the WebSocket in an afterEach or try/finally.
- One test() per scenario; use async/await.
- Structure: // Arrange / // Act / // Assert comments.
- Positive: connect, sendAndReceive, assert response fields.
- Negative: expect the connect or sendAndReceive to throw, OR assert error fields in response.
- Output ONLY valid JavaScript. No markdown fences, no explanation."""

JEST_STANDARDS_BY_TYPE: dict[APIType, str] = {
    APIType.REST: _REST_JEST_STANDARDS,
    APIType.GRAPHQL: _GRAPHQL_JEST_STANDARDS,
    APIType.SOAP: _REST_JEST_STANDARDS,       # SOAP via axios raw XML (fallback)
    APIType.GRPC: _REST_JEST_STANDARDS,       # gRPC-web via axios (fallback)
    APIType.WEBSOCKET: _WEBSOCKET_JEST_STANDARDS,
}


def validate_jest_source(source: str) -> None:
    if "test(" not in source and "it(" not in source:
        raise ValueError("Generated Jest source contains no test() or it() calls")


def jest_test_filename(ticket_id: str) -> str:
    slug = ticket_id.lower().replace("-", "_")
    return f"test_{slug}.test.js"
