def build_jest_config() -> str:
    return dedent(
        """\
        /** @type {import('jest').Config} */
        module.exports = {
          testEnvironment: 'node',
          testTimeout: 30000,
          verbose: true,
        };
        """
    )


def build_package_json(ticket_id: str) -> str:
    slug = ticket_id.lower().replace("-", "_")
    pkg = {
        "name": f"qa-tests-{ticket_id.lower()}",
        "version": "1.0.0",
        "description": f"Generated QA automation tests for {ticket_id}",
        "scripts": {
            "test": "jest",
            "test:verbose": "jest --verbose",
        },
        "devDependencies": {
            "jest": "^29.0.0",
            "axios": "^1.7.0",
        },
    }
    return json.dumps(pkg, indent=2)


def build_jest_setup(ticket_id: str, base_url: str, api_type: APIType) -> str:
    """Return a setup.js file with shared helpers per API type."""
    if api_type == APIType.GRAPHQL:
        return _jest_setup_graphql(ticket_id, base_url)
    if api_type == APIType.WEBSOCKET:
        return _jest_setup_websocket(ticket_id, base_url)
    return _jest_setup_rest(ticket_id, base_url)


def _jest_setup_rest(ticket_id: str, base_url: str) -> str:
    return dedent(
        f"""\
        /**
         * Shared setup for {ticket_id} REST automation tests.
         * Generated by QA Script Generator.
         */
        const axios = require('axios');

        const BASE_URL = process.env.API_BASE_URL || {json.dumps(base_url)};
        const API_KEY  = process.env.API_KEY || '';

        function createClient() {{
          return axios.create({{
            baseURL: BASE_URL,
            timeout: 30000,
            headers: {{
              'Content-Type': 'application/json',
              ...(API_KEY ? {{ Authorization: `Bearer ${{API_KEY}}` }} : {{}}),
            }},
            validateStatus: () => true,   // never throw on non-2xx; assert manually
          }});
        }}

        module.exports = {{ BASE_URL, API_KEY, createClient }};
        """
    )


def _jest_setup_graphql(ticket_id: str, graphql_url: str) -> str:
    return dedent(
        f"""\
        /**
         * Shared setup for {ticket_id} GraphQL tests.
         * Generated by QA Script Generator.
         */
        const axios = require('axios');

        const GRAPHQL_URL = process.env.GRAPHQL_URL || {json.dumps(graphql_url)};
        const API_KEY     = process.env.API_KEY || '';

        function createGqlClient() {{
          return axios.create({{
            baseURL: GRAPHQL_URL,
            timeout: 30000,
            headers: {{
              'Content-Type': 'application/json',
              ...(API_KEY ? {{ Authorization: `Bearer ${{API_KEY}}` }} : {{}}),
            }},
            validateStatus: () => true,
          }});
        }}

        async function gql(client, query, variables = null) {{
          const body = {{ query }};
          if (variables) body.variables = variables;
          return client.post('', body);
        }}

        module.exports = {{ GRAPHQL_URL, API_KEY, createGqlClient, gql }};
        """
    )


def _jest_setup_websocket(ticket_id: str, ws_url: str) -> str:
    ws = ws_url.replace("https://", "wss://").replace("http://", "ws://")
    return dedent(
        f"""\
        /**
         * Shared setup for {ticket_id} WebSocket tests.
         * Generated by QA Script Generator.
         * Requires: npm install ws
         */
        const WebSocket = require('ws');

        const WS_URL = process.env.WS_URL || {json.dumps(ws)};

        function connect(url = WS_URL, timeout = 5000) {{
          return new Promise((resolve, reject) => {{
            const ws = new WebSocket(url);
            const timer = setTimeout(() => {{ ws.close(); reject(new Error('WS connect timeout')); }}, timeout);
            ws.on('open', () => {{ clearTimeout(timer); resolve(ws); }});
            ws.on('error', (err) => {{ clearTimeout(timer); reject(err); }});
          }});
        }}

        function sendAndReceive(ws, payload, timeout = 5000) {{
          return new Promise((resolve, reject) => {{
            const timer = setTimeout(() => reject(new Error('WS recv timeout')), timeout);
            ws.once('message', (data) => {{ clearTimeout(timer); resolve(JSON.parse(data.toString())); }});
            ws.send(JSON.stringify(payload));
          }});
        }}

        module.exports = {{ WS_URL, connect, sendAndReceive }};
        """
    )


